/**
 * The API's field messages are English. Screens show their own wording instead:
 * the field's hint when it explains the format, otherwise a plain "check this field".
 */
export function localFieldErrors(apiErrors: Record<string, string>, s: Strings, hints: Record<string, string> = {}) {
  return Object.fromEntries(Object.keys(apiErrors).map((path) => [path, hints[path] ?? s.checkField]));
}
